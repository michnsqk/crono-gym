export const CRONOS_MACHINERY_EXERCISES: readonly CatalogExercise[] = SPECS.map(makeMachineryRow);

function normalizeText(value: string | null | undefined): string {
  return (value ?? "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

/**
 * Merges curated machinery exercises without duplicating any base or custom row
 * that already shares the same id or normalised name/Spanish name.
 */
export function mergeMachineryExercises(
  baseRows: readonly CatalogExercise[],
  seedRows: readonly CatalogExercise[] = CRONOS_MACHINERY_EXERCISES,
): CatalogExercise[] {
  const seenIds = new Set<string>();
  const seenNames = new Set<string>();

  for (const row of baseRows) {
    seenIds.add(row.id);
    const n1 = normalizeText(row.name);
    const n2 = normalizeText(row.name_es);
    if (n1) seenNames.add(n1);
    if (n2) seenNames.add(n2);
  }

  const extras: CatalogExercise[] = [];
  for (const seed of seedRows) {
    if (seenIds.has(seed.id)) continue;
    const n1 = normalizeText(seed.name);
    const n2 = normalizeText(seed.name_es);
    if ((n1 && seenNames.has(n1)) || (n2 && seenNames.has(n2))) continue;
    seenIds.add(seed.id);
    if (n1) seenNames.add(n1);
    if (n2) seenNames.add(n2);
    extras.push(seed);
  }

  return extras.length === 0 ? (baseRows as CatalogExercise[]) : [...baseRows, ...extras];
}
